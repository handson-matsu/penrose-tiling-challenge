// Robinson-triangle subdivision of the ten-triangle sun. Incomplete boundary rhombs are omitted.
import {PHI,add,sub,mul,distance,near,vertices,edge,edgeKey,matches,topology} from '../geometry.js';
export function sun(depth=4) {
 let triangles=Array.from({length:10},(_,i)=>{
  let b=[Math.cos((2*i-1)*Math.PI/10),Math.sin((2*i-1)*Math.PI/10)], c=[Math.cos((2*i+1)*Math.PI/10),Math.sin((2*i+1)*Math.PI/10)];
  if(i%2===0)[b,c]=[c,b];return {type:0,a:[0,0],b,c};
 });
 for(let n=0;n<depth;n++) triangles=triangles.flatMap(({type,a,b,c})=>{
  if(type===0){const p=add(a,mul(sub(b,a),1/PHI));return [{type:0,a:c,b:p,c:b},{type:1,a:p,b:c,c:a}];}
  const q=add(b,mul(sub(a,b),1/PHI)),r=add(b,mul(sub(c,b),1/PHI));
  return [{type:1,a:r,b:c,c:a},{type:1,a:q,b:r,c:b},{type:0,a:r,b:q,c:a}];
 });
 const map=new Map(),tiles=[];
 for(const tr of triangles){const key=edgeKey(tr.b,tr.c);if(!map.has(key)){map.set(key,tr);continue;}
  const other=map.get(key);map.delete(key);if(tr.type!==other.type)throw Error('Triangle pairing');
  const type=tr.type===0?'thin':'thick';const center=mul(add(tr.b,tr.c),.5),left=type==='thin'?tr.a:tr.b;
  const scale=distance(tr.a,tr.b),p=mul(center,1/scale),v=sub(left,center);
  tiles.push({type,x:p[0],y:p[1],angle:Math.atan2(v[1],v[0])-Math.PI});
 }
 // Each geometric rhomb has two possible rotations. Solve the independent arrow decorations
 // by propagating compatibility across known shared edges (no geometric placement is generated by this solver).
 const adjacency=topology(tiles).shared, domains=tiles.map(()=>[0,1]);
 const variant=(k,v)=>({...tiles[k],angle:tiles[k].angle+v*Math.PI});
 const constraints=adjacency.map(([a,b])=>({a:a.tile,b:b.tile,i:a.i,j:b.i}));
 function solve(dom){let changed=true;while(changed){changed=false;for(const c of constraints)for(const reverse of [false,true]){
  const a=reverse?c.b:c.a,b=reverse?c.a:c.b,i=reverse?c.j:c.i,j=reverse?c.i:c.j;
  const valid=dom[a].filter(v=>dom[b].some(w=>matches(variant(a,v),(i+2*v)%4,variant(b,w),(j+2*w)%4)));
  if(!valid.length)return null;if(valid.length!==dom[a].length){dom[a]=valid;changed=true;}
 }}const k=dom.findIndex(d=>d.length>1);if(k<0)return dom;for(const v of dom[k]){const next=dom.map(d=>[...d]);next[k]=[v];const result=solve(next);if(result)return result;}return null;}
 const solution=solve(domains);if(!solution)throw Error('No standard P3 decoration for sun');
 return tiles.map((t,k)=>variant(k,solution[k][0]));
}
